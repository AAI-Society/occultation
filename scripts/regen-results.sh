write_composed_facts() {
  local out=results/measured/composed-facts.tex
  local src=results/measured/composed.json
  local desk_total measured_total mv_naive mv_cached ratio_baseline mp_naive mp_pooled

  read -r desk_total measured_total mv_naive mv_cached ratio_baseline mp_naive mp_pooled < <(
    jq -r '[.desk_study[0].composed.total_us, .measured[0].composed.total_us,
             .measured[0].composed.verify_us, .measured[1].composed.verify_us,
             .measured_ratio_to_baseline,
             .measured[0].composed.present_us, .measured[2].composed.present_us] | @tsv' "$src"
  )
  local factor direction measured_pct ratio_i pooled_pct factor_excl_escrow
  factor=$(awk -v d="$desk_total" -v m="$measured_total" \
    'BEGIN{a=d/m; b=m/d; printf "%.0f", (a>b?a:b)}')
  direction=$(awk -v d="$desk_total" -v m="$measured_total" \
    'BEGIN{print (m<d)?"cheaper":"dearer"}')
  measured_pct=$(awk -v n="$mv_naive" -v c="$mv_cached" 'BEGIN{printf "%.0f", (1-c/n)*100}')
  ratio_i=$(awk -v n="$ratio_baseline" 'BEGIN{printf "%.0f", n}')
  # 1 - (pooled ESTIMATED present) / (naive present), on this host. Companion
  # to \deskpooledreductionpct in results/deterministic/desk-facts.tex, which
  # is the same ratio over the desk study's published constants instead of a
  # measurement here; the two are expected to differ, which is the point of
  # the sentence that cites them.
  pooled_pct=$(awk -v n="$mp_naive" -v c="$mp_pooled" 'BEGIN{printf "%.0f", (1-c/n)*100}')
  # \measureddivergencefactor above is not an apples-to-apples comparison: the
  # desk study's naive presentation figure (part of desk_total) bakes in a
  # 4.6ms/33% allowance for the escrow tag (see src/bench.rs's
  # `composed_report_with`'s "excludes the escrow tag" note, which states the
  # same 4.6ms figure), while the measured figure here excludes escrow
  # entirely. 4600us matches that same literal; excluding escrow from both
  # sides instead gives this divergence factor, for main.tex to cite beside
  # \measureddivergencefactor rather than in place of it.
  factor_excl_escrow=$(awk -v d="$desk_total" -v e=4600 -v m="$measured_total" \
