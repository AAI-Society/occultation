#!/usr/bin/env bash
# Regenerate every number the paper cites.
#
# results/deterministic/ is byte-identical on any host: it is arithmetic over
# published figures, a seeded simulation, and a partition of a fixed input
# file. CI regenerates it and fails on a diff.
#
# That byte-identity depends on one thing that is not obvious and that this
# script cannot enforce: the JSON writers sort their keys explicitly, through
# src/report.rs::canonical_json. serde_json::Map is a BTreeMap only while
# nothing in the dependency graph enables `preserve_order` — dcap-qvl does,
# graph-wide, and the day it arrived every file under deterministic/ silently
# changed its bytes (key order only; values identical) with nothing in this
# repository touched. See results/README.md for the whole account. If a diff
# ever appears here that is purely key order, that is the symptom, and the
# fix is in the writers, never in this script and never by committing the
# reordered files.
#
# results/measured/ is wall-clock timing and differs per host. CI regenerates
# it and checks its schema and tool version, but cannot diff it: a build that
# failed because the machine was 3% busier would train everyone to ignore CI.
#
# This script also emits the `tabular` files paper/main.tex `\input`s under
# \section{Results}: composed-table.tex and anonymity-table.tex are
# arithmetic over the desk study's published constants and a fixed fleet
# file respectively, so they are exactly as host-independent as the JSON
# they are read from and belong in deterministic/, diffed by CI.
# primitives-table.tex is read from the wall-clock primitives.json and
# belongs in measured/, not diffed, for the same reason primitives.json
# itself is not. Every number in these files is read out of already-written
# JSON with jq; nothing here is typed by hand.
#
# Four more files beyond the three tables the paper's task brief names, all
# defining \newcommand macros for figures the paper's prose cites but that do
# not belong in any of the three tables:
#   - desk-facts.tex (deterministic; arithmetic over the desk study's own
#     published constants, the same ones Table 3 reads) and
#     anonymity-facts.tex (deterministic; the same fleet partition Table 5
#     reads) restate figures the abstract and Problem statement quote before
#     their tables appear, so the prose cannot silently drift from the table
#     it is summarizing.
#   - pool-facts.tex (deterministic; a seeded burst simulation) defines the
#     pool's capacity/seed/amplification/overload/growth figures.
#   - composed-facts.tex (measured; wall-clock, not diffed) defines the
#     measured-vs-published divergence factor and the measured-host cached-
#     pairing saving and pooled-reduction percentages; their desk-study
#     counterparts live in desk-facts.tex instead, because those are
#     constants, not measurements, and belong in the diffed half.
# The paper's governing constraint is that no number is typed by hand; these
# exist so that constraint holds outside the tables too.
set -euo pipefail
cd "$(dirname "$0")/.."
cargo build --release --quiet
BIN=./target/release/occultation
mkdir -p results/deterministic results/measured

# --- deterministic -----------------------------------------------------
"$BIN" anonymity --fleet examples/fleet-uniform.toml --format json \
  > results/deterministic/anonymity-uniform.json
"$BIN" anonymity --fleet examples/fleet-drifted.toml --format json \
  > results/deterministic/anonymity-drifted.json
"$BIN" anonymity --fleet examples/fleet-drifted.toml \
  > results/deterministic/anonymity-drifted.txt

for rate in 500 2000 5000; do
  "$BIN" pool --burst "$rate" --duration 2s --capacity 64 \
      --refill 700us --online 60us --seed 7 --format json \
    > "results/deterministic/pool-burst-$rate.json"
done
"$BIN" pool --burst 5000 --duration 2s --capacity 64 --refill 700us --online 60us --seed 7 \
  > results/deterministic/pool-burst-5000.txt

# --- measured ----------------------------------------------------------
# --iters is high enough that the median is stable and low enough that CI
# finishes. The host and toolchain are recorded so a stale file is obvious.
{
  echo "# generated by scripts/regen-results.sh"
  echo "# tool_version: $("$BIN" --version)"
  echo "# host: $(uname -sm)"
  echo "# rustc: $(rustc --version)"
} > results/measured/HEADER.txt

"$BIN" bench --iters 200 --format json > results/measured/primitives.json
"$BIN" bench --iters 200 > results/measured/primitives.txt
"$BIN" bench --composed --iters 200 --format json > results/measured/composed.json
"$BIN" bench --composed --iters 200 > results/measured/composed.txt

# --- LaTeX tables for the paper -----------------------------------------
# Force the C locale for number formatting so a decimal comma locale cannot
# make these files (composed-table.tex, anonymity-table.tex) fail the CI
# diff on a contributor's machine.
export LC_ALL=C

# Milliseconds, two decimal places, matching src/cost.rs's fmt_ms. Takes
# microseconds: `Composed`'s Duration fields serialize as `*_us` numbers
# (src/cost.rs's `duration_us` module), not the nanosecond `{secs, nanos}`
# shape this script used to read via `.nanos`.
fmt_ms() {
  awk -v n="$1" 'BEGIN{printf "%.2f", n / 1000}'
}

# Escape LaTeX's special characters in a string pulled from JSON before it is
# interpolated into a generated .tex file. Labels are Rust string literals
# today (e.g. "hash_to_scalar") and TCB fields are operator-supplied TOML, so
# an unescaped `_`, `&`, `%` or `#` is one label rename or one fleet file away
# from a tectonic build that fails, or worse, one that silently drops text.
#
# Implemented with sed, not bash's `${var//pattern/replacement}`: a
# replacement containing a literal `}` (needed for \}, \textbackslash{}, and
# friends) makes bash miscount the braces that close the parameter expansion
# itself and truncates the substitution — verified the hard way, by watching
# every row in a generated table grow a stray trailing `}`. Backslash goes to
# a placeholder token first so it is not re-escaped by the rules after it.
latex_escape() {
  printf '%s' "$1" | sed \
    -e 's/\\/OCCULTATIONBACKSLASHTOKEN/g' \
    -e 's/&/\\\&/g' \
    -e 's/%/\\%/g' \
    -e 's/\$/\\$/g' \
    -e 's/#/\\#/g' \
    -e 's/_/\\_/g' \
    -e 's/{/\\{/g' \
    -e 's/}/\\}/g' \
    -e 's/~/\\textasciitilde{}/g' \
    -e 's/\^/\\textasciicircum{}/g' \
    -e 's/OCCULTATIONBACKSLASHTOKEN/\\textbackslash{}/g'
}

# Mirrors the three BudgetVerdict variants' Display impl in src/cost.rs.
fmt_verdict() {
  local kind="$1" ns="$2" ms
  ms=$(fmt_ms "$ns")
  case "$kind" in
    misses)   printf 'MISSES by %s\\,ms' "$ms" ;;
    marginal) printf 'MARGINAL --- %s\\,ms spare' "$ms" ;;
    fits)     printf 'fits, %s\\,ms spare' "$ms" ;;
    *) echo "regen-results.sh: unrecognized verdict kind '$kind' in composed.json" >&2; exit 1 ;;
  esac
}

# Desk-study constants used in prose outside the Results section (the
# abstract and the Problem statement set the scene with these before any
# table appears). They are read from the same composed.json field the table
# itself reads, formatted the same way (fmt_ms), so the abstract cannot
# quietly drift from Table 3 by a rounding choice made in two places.
write_desk_facts() {
  local out=results/deterministic/desk-facts.tex
  local budget_us present_us verify_us total_us over_us cached_total_us \
    cached_headroom_us pooled_present_us cached_verify_us pooled_total_us pooled_headroom_us

  budget_us=$(jq -r '.desk_study[0].composed.budget_us' results/measured/composed.json)
  present_us=$(jq -r '.desk_study[0].composed.present_us' results/measured/composed.json)
  verify_us=$(jq -r '.desk_study[0].composed.verify_us' results/measured/composed.json)
  total_us=$(jq -r '.desk_study[0].composed.total_us' results/measured/composed.json)
  over_us=$(jq -r '.desk_study[0].composed.verdict.over_us' results/measured/composed.json)
  cached_total_us=$(jq -r '.desk_study[1].composed.total_us' results/measured/composed.json)
  cached_headroom_us=$(jq -r '.desk_study[1].composed.verdict.headroom_us' results/measured/composed.json)
  cached_verify_us=$(jq -r '.desk_study[1].composed.verify_us' results/measured/composed.json)
  pooled_present_us=$(jq -r '.desk_study[2].composed.present_us' results/measured/composed.json)
  pooled_total_us=$(jq -r '.desk_study[2].composed.total_us' results/measured/composed.json)
  pooled_headroom_us=$(jq -r '.desk_study[2].composed.verdict.headroom_us' results/measured/composed.json)

  # Two ratios computed from the desk study's own published constants above
  # (not from anything measured on this host), so, unlike
  # \measuredcachedsavingpct and \pooledreductionpct in
  # results/measured/composed-facts.tex, these belong under deterministic/
  # and are diffed by CI: a code change cannot silently move them without
  # tripping the diff.
  local cached_saving_pct pooled_reduction_pct
  cached_saving_pct=$(awk -v n="$verify_us" -v c="$cached_verify_us" 'BEGIN{printf "%.0f", (1-c/n)*100}')
  pooled_reduction_pct=$(awk -v n="$present_us" -v c="$pooled_present_us" 'BEGIN{printf "%.0f", (1-c/n)*100}')

  cat > "$out" <<EOF
% Generated by scripts/regen-results.sh from the desk_study rows of
% results/measured/composed.json (the same field Table 3 reads). These are
% the desk study's published constants, quoted in prose before Table 3
% appears; formatted identically to it so the two cannot silently diverge.
\newcommand{\deskbudget}{\SI{$(fmt_ms "$budget_us")}{\milli\second}}
\newcommand{\deskpresentnaive}{\SI{$(fmt_ms "$present_us")}{\milli\second}}
\newcommand{\deskverifynaive}{\SI{$(fmt_ms "$verify_us")}{\milli\second}}
\newcommand{\desktotalnaive}{\SI{$(fmt_ms "$total_us")}{\milli\second}}
\newcommand{\deskovernaive}{\SI{$(fmt_ms "$over_us")}{\milli\second}}
\newcommand{\desktotalcached}{\SI{$(fmt_ms "$cached_total_us")}{\milli\second}}
\newcommand{\deskheadroomcached}{\SI{$(awk -v n="$cached_headroom_us" 'BEGIN{printf "%.0f", n}')}{\micro\second}}
\newcommand{\deskverifycached}{\SI{$(fmt_ms "$cached_verify_us")}{\milli\second}}
\newcommand{\deskpresentpooled}{\SI{$(fmt_ms "$pooled_present_us")}{\milli\second}}
\newcommand{\desktotalpooled}{\SI{$(fmt_ms "$pooled_total_us")}{\milli\second}}
\newcommand{\deskheadroompooled}{\SI{$(fmt_ms "$pooled_headroom_us")}{\milli\second}}
\newcommand{\deskcachedsavingpct}{\SI{$cached_saving_pct}{\percent}}
\newcommand{\deskpooledreductionpct}{\SI{$pooled_reduction_pct}{\percent}}
EOF
}

write_composed_table() {
  local out=results/deterministic/composed-table.tex
  local budget_us naive_total naive_over cached_total cached_headroom pooled_total pooled_headroom

  budget_us=$(jq -r '.desk_study[0].composed.budget_us' results/measured/composed.json)
  naive_total=$(jq -r '.desk_study[0].composed.total_us' results/measured/composed.json)
  naive_over=$(jq -r '.desk_study[0].composed.verdict.over_us' results/measured/composed.json)
  cached_total=$(jq -r '.desk_study[1].composed.total_us' results/measured/composed.json)
  cached_headroom=$(jq -r '.desk_study[1].composed.verdict.headroom_us' results/measured/composed.json)
  pooled_total=$(jq -r '.desk_study[2].composed.total_us' results/measured/composed.json)
  pooled_headroom=$(jq -r '.desk_study[2].composed.verdict.headroom_us' results/measured/composed.json)

  cat > "$out" <<'HEADER'
% Generated by scripts/regen-results.sh from the desk_study rows of
% results/measured/composed.json. Those rows are the desk study's published
% figures, which are constants and do not vary by host, so this file lives
% under deterministic/ and is diffed by CI. Do not hand-edit.
\begin{table}[h]
\centering\small
\begin{tabular}{>{\raggedright\arraybackslash}p{4.3cm}rrr>{\raggedright\arraybackslash}p{3.7cm}}
\toprule
Composition & Present & Verify & Total & Verdict \\
\midrule
HEADER

  jq -r '.desk_study[] | [.label, .composed.present_us, .composed.verify_us,
          .composed.total_us, .composed.verdict.verdict,
          (.composed.verdict.over_us // .composed.verdict.headroom_us // 0)] | @tsv' \
    results/measured/composed.json |
  while IFS=$'\t' read -r label present verify total vkind vextra; do
    p=$(fmt_ms "$present"); v=$(fmt_ms "$verify"); t=$(fmt_ms "$total")
    verdict=$(fmt_verdict "$vkind" "$vextra")
    printf '%s & %s\\,ms & %s\\,ms & %s\\,ms & %s \\\\\n' "$(latex_escape "$label")" "$p" "$v" "$t" "$verdict"
  done >> "$out"

  local caption
  caption=$(printf 'The composed present-and-verify path against the %s\\,ms budget: the desk study'"'"'s published figures for presentation and verification, assessed together rather than separately as the desk study assessed them. The naive composition sums to %s\\,ms and misses the budget by %s\\,ms even though each half alone appeared to fit. Caching pairings brings the sum to %s\\,ms, %s\\,ms under the limit --- not headroom, hence \\texttt{MARGINAL} rather than a pass. Only the pre-computation pool, combined with cached pairings, fits with room to spare: %s\\,ms total, %s\\,ms of headroom. \\texttt{results/\\allowbreak measured/\\allowbreak composed.txt} reports the profile measured on this host, which diverges from these published figures by roughly an order of magnitude without changing the correction, which is an error in arithmetic, not in hardware.' \
    "$(fmt_ms "$budget_us")" "$(fmt_ms "$naive_total")" "$(fmt_ms "$naive_over")" \
    "$(fmt_ms "$cached_total")" "$(fmt_ms "$cached_headroom")" \
    "$(fmt_ms "$pooled_total")" "$(fmt_ms "$pooled_headroom")")

  {
    echo '\bottomrule'
    echo '\end{tabular}'
    printf '\\caption{%s}\n' "$caption"
    echo '\label{tab:composed}'
    echo '\end{table}'
  } >> "$out"
}

